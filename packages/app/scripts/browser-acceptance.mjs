// Synthetic HTTPS browser acceptance. No real provider, microphone or family data.
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { createServer } from 'node:https';
import { once } from 'node:events';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import sharp from 'sharp';
import { syntheticWebm } from '../tests/helpers/synthetic-video.mjs';
import { integratedFixture } from '../tests/helpers/integrated-app-fixture.mjs';
import { createNodeRequestListener } from '../src/server/host.mjs';
import { decodeArchiveFiles } from '../src/server/archive-transport.mjs';
import { inspectFamilyArchive } from '../src/core/family-archive.mjs';
import { webcrypto } from 'node:crypto';
const cleanups = [];
const tls = await mkdtemp(join(tmpdir(), 'being-there-test-tls-'));
let server, browser;
try {
  execFileSync('openssl', ['req', '-x509', '-newkey', 'rsa:2048', '-nodes', '-keyout', join(tls, 'key.pem'), '-out', join(tls, 'cert.pem'), '-subj', '/CN=localhost', '-days', '1'], { stdio: 'ignore' });
  let listener;
  server = createServer({ key: await readFile(join(tls, 'key.pem')), cert: await readFile(join(tls, 'cert.pem')) }, (req, res) => listener(req, res));
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const origin = 'https://127.0.0.1:' + server.address().port;
  const fixture = await integratedFixture({ after: callback => cleanups.push(callback) }, { originOverride: origin });
  listener = createNodeRequestListener({ handle: request => fixture.app.handle(request), appOrigin: origin });
  const owner = await fixture.login('browser-owner', 'owner@family.example.test'); assert.equal(owner.callback.status, 303);
  const invitation = fixture.repository.bootstrapInvitation({ familyId: 'familyA', label: 'Fictional browser household', email: 'owner@family.example.test' });

  browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}), args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] });
  const context = await browser.newContext({ ignoreHTTPSErrors: true, acceptDownloads: true, viewport: { width: 1280, height: 900 }, permissions: ['microphone'] });
  await context.addCookies(owner.cookie.split('; ').map(pair => { const offset = pair.indexOf('='); return { name: pair.slice(0, offset), value: pair.slice(offset + 1), url: origin, secure: true, httpOnly: pair.startsWith('__Host-being-there-session='), sameSite: 'Lax' }; }));
  const page = await context.newPage(); const errors = [], external = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (!request.url().startsWith(origin) && !request.url().startsWith('blob:')) external.push(new URL(request.url()).origin); });
  await page.goto(origin + '/?invite=' + invitation.token);
  await page.locator('#nickname').fill('Fictional owner');
  await page.getByRole('button', { name: 'Accept invitation', exact: true }).click();
  await page.locator('#organizer').waitFor({ state: 'visible' });
  await page.locator('#organizer > summary').click();
  for (const name of ['Avery (fictional)', 'Riley (fictional)']) {
    await page.locator('#person-name').fill(name); await page.getByRole('button', { name: 'Add person', exact: true }).click();
    await page.waitForFunction(() => document.getElementById('person-name').value === '');
  }
  await page.locator('#contribute > summary').click();
  const photo = await sharp({ create: { width: 320, height: 240, channels: 3, background: '#73a578' } }).png().toBuffer();
  await page.locator('#file').setInputFiles({ name: 'fictional-garden.png', mimeType: 'image/png', buffer: photo });
  await page.locator('#caption').fill('A fictional garden afternoon');
  const people = await page.locator('#upload-people option').evaluateAll(options => options.map(option => option.value));
  assert.equal(people.length, 2); await page.locator('#upload-people').selectOption(people);
  await page.getByRole('button', { name: 'Share media', exact: true }).click();
  await page.waitForFunction(() => document.getElementById('photo').complete && document.getElementById('photo').naturalWidth > 0);
  await page.locator('#story-text').fill('A separate fictional perspective. <img src=x onerror=alert(1)>');
  await page.getByRole('button', { name: 'Share these words', exact: true }).click();
  await page.locator('#stories').getByText('A separate fictional perspective.', { exact: false }).waitFor();
  assert.equal(await page.locator('#stories img').count(), 0);
  await page.getByRole('button', { name: 'Record a story', exact: true }).click();
  await page.locator('#stop').waitFor({ state: 'visible' });
  await page.waitForTimeout(5500);
  await page.getByRole('button', { name: 'Finish recording', exact: true }).click();
  await page.getByRole('button', { name: 'Send saved recording', exact: true }).waitFor();
  const storyPattern = '**/api/families/*/memories/*/stories';
  await page.route(storyPattern, async route => { if (route.request().method() !== 'POST') return route.continue(); const committed = await route.fetch(); assert.equal(committed.status(), 200); return route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Synthetic interrupted acknowledgment' }) }); });
  await page.getByRole('button', { name: 'Send saved recording', exact: true }).click();
  await page.waitForFunction(() => document.getElementById('status').textContent.includes('Synthetic interrupted acknowledgment'));
  assert.equal(await page.locator('#pending button').count(), 1);
  await page.unroute(storyPattern); await page.reload();
  await page.getByRole('button', { name: 'Send saved recording', exact: true }).click();
  await page.waitForFunction(() => document.getElementById('status').textContent === 'Your story is preserved.');
  await page.locator('#stories audio').waitFor();
  await page.locator('#stories audio').evaluate(audio => { audio.preload = 'metadata'; audio.load(); });
  await page.waitForFunction(() => document.querySelector('#stories audio')?.readyState >= 1, null, { timeout: 10000 }).catch(async error => { console.log(await page.locator('#stories audio').evaluate(audio => ({ error: audio.error?.code, network: audio.networkState, ready: audio.readyState, type: audio.currentSrc, supports: audio.canPlayType('audio/webm;codecs=opus') }))); throw error; });
  assert.equal(await page.locator('#pending button').count(), 0);
  // Reload closes details; reopen family contribution tools before the second upload.
  await page.locator('#contribute > summary').click();
  // Verify video uses the real upload API, browser player, byte-preserved scoped transport.
  await page.locator('#file').setInputFiles({ name: 'fictional-video.webm', mimeType: 'video/webm', buffer: syntheticWebm });
  await page.locator('#caption').fill('A fictional little video');
  await page.locator('#upload-people').selectOption(people);
  await page.getByRole('button', { name: 'Share media', exact: true }).click();
  await page.waitForFunction(() => document.getElementById('status').textContent.includes('Video shared'));
  for (let n = 0; n < 2 && !(await page.locator('#video').isVisible()); n++)
    await page.getByRole('button', { name: 'Next memory', exact: false }).click();
  assert.equal(await page.locator('#video').isVisible(), true, 'Short video must be in family rotation');
  await page.locator('#video').evaluate(video => { video.preload = 'metadata'; video.load(); });
  await page.waitForFunction(() => document.querySelector('#video')?.readyState >= 1, null, { timeout: 10000 });
  assert.equal(await page.locator('#video').evaluate(video => video.videoWidth > 0 && video.duration > 0), true);
  for (let n = 0; n < 2 && !(await page.locator('#photo').isVisible()); n++)
    await page.getByRole('button', { name: 'Next memory', exact: false }).click();
  assert.equal(await page.locator('#photo').isVisible(), true);
  await page.locator('#organizer > summary').click();
  const downloadWait = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download a verified family archive', exact: true }).click();
  const download = await downloadWait; const source = await download.createReadStream(); const parts = [];
  for await (const part of source) parts.push(part);
  const files = decodeArchiveFiles(JSON.parse(Buffer.concat(parts).toString()));
  const checked = await inspectFamilyArchive({ files, expectedFamilyId: 'familyA', subtleCrypto: webcrypto.subtle });
  assert.equal(checked.content.people.length, 2); assert.equal(checked.content.stories.length, 2); assert.equal(checked.content.originals.length, 3);
  if (process.env.BROWSER_QA_SCREENSHOTS) await page.screenshot({ path: '/tmp/being-there-family-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole('button', { name: 'Enjoy memories', exact: true }).click();
  assert.equal(await page.locator('#enjoy-view').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('#organizer').isVisible(), false);
  assert.equal(await page.locator('#photo').isVisible(), true);
  await page.getByRole('button', { name: 'Next memory', exact: false }).click();
  await page.waitForFunction(() => document.activeElement.id === 'memory-title');
  if (process.env.BROWSER_QA_SCREENSHOTS) await page.screenshot({ path: '/tmp/being-there-family-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.getByRole('link', { name: 'Sign in with Google', exact: true }).waitFor();
  assert.equal(await page.locator('#app').isVisible(), false);
  assert.equal(await page.evaluate(async () => (await fetch('/api/families/familyA/memories')).status), 401);
  assert.deepEqual(errors, []); assert.deepEqual(external, []);
  console.log('Synthetic HTTPS browser acceptance passed: onboarding, upload, text, recoverable recording, real playback metadata, verified export, mobile layout, keyboard focus and logout. No real provider or microphone used.');
} finally {
  if (browser) await browser.close();
  if (server) await new Promise(resolve => { server.close(resolve); server.closeAllConnections(); });
  for (const callback of cleanups.reverse()) await callback();
  await rm(tls, { recursive: true, force: true });
}
